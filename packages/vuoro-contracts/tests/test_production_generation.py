def test_source_output_links_and_unmarked_output_are_refused(tmp_path):
    outside = tmp_path / "outside"
    outside.mkdir()
    (outside / "keep").write_bytes(b"unchanged")
    linked = tmp_path / "link"
    linked.symlink_to(outside, target_is_directory=True)
    with pytest.raises(ContractError): invoke(linked, "--write")
    with pytest.raises(ContractError): invoke(outside, "--write")
    assert inventory(outside) == {"keep": sha256(b"unchanged").hexdigest()}
    source = tmp_path / "source"
    shutil.copytree(SOURCE, source, ignore=shutil.ignore_patterns("node_modules", ".venv"))
    original = source / "original.tsp"
    (source / "main.tsp").rename(original)
    (source / "main.tsp").symlink_to(original)
    with pytest.raises(ContractError): invoke(tmp_path / "linked-source-output", "--write", source=source)


