def test_failed_compilation_preserves_existing_output_and_source(tmp_path, generated):
    source = tmp_path / "source"
    shutil.copytree(SOURCE, source, ignore=shutil.ignore_patterns("node_modules", ".venv"))
    (source / "main.tsp").write_text((source / "main.tsp").read_text() + "\nTHIS IS NOT TYPESPEC;\n")
    out = tmp_path / "out"
