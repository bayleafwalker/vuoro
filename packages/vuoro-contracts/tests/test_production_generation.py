def _replace_once(source, old, new):
    assert source.count(old) == 1, "qualified Hey API observation anchor changed"
    return source.replace(old, new)


def _build_ts_oracle(generated, stage, oracle_name):
    shutil.copytree(generated / "clients/typescript", stage / "client")
    attachment = stage / "client/validated-sdk.ts"
    runner = (ORACLES / oracle_name).read_text()
    replacements = {"__ATTACHMENT__": str(attachment), "__DECODER__": str(stage / "client/strict-json.ts"), "__SDK__": str(stage / "client/sdk.gen.ts"),
                    "__CLIENT__": str(stage / "client/client/index.ts"), "__AJV__": str(TOOLS / "node_modules/ajv/dist/2020.js")}
    manifest = json.loads((generated / "operation-manifest.json").read_bytes())
    for old, new in replacements.items(): runner = runner.replace(old, new)
    vector_json = (TOOLS / "fixtures/wire-vectors.json").read_text()
    runner = runner.replace("__WIRE_VECTORS_JSON__", json.dumps(vector_json))
    runner = runner.replace("__MANIFEST_LITERAL__", json.dumps(manifest))
    runner = runner.replace("__BUNDLE_LITERAL__", (generated / manifest["schemaBundle"]["path"]).read_text())
    if oracle_name == "typescript_sdk_oracle.ts":
        path = stage / "client/client/client.gen.ts"
        native = path.read_text()
        native = _replace_once(native, "const request: Client['request'] = async (options) => {", "const request: Client['request'] = async (options) => {\n(globalThis as any).__vuoroOracle.native++;")
        native = _replace_once(native, "await opts.requestValidator(opts);", "(globalThis as any).__vuoroOracle.requestValidator++;\nawait opts.requestValidator(opts);")
        original = "opts.serializedBody = opts.bodySerializer(opts.body) as string | undefined;"
        native = _replace_once(native, original, "(globalThis as any).__vuoroOracle.serializer++;\n" + original + "\nconst mutation = (globalThis as any).__vuoroOracle.serializeMutation; if (mutation) { let raw = opts.serializedBody!; if (mutation === 'unknown' || mutation === 'counter') { const b = JSON.parse(raw); if (mutation === 'unknown') b.unexpected = 'PRIVATE_WIRE_MARKER'; else b.revision = 9007199254740995; raw = JSON.stringify(b); } if (mutation === 'duplicate') raw = raw.slice(0,-1) + ',\"revision\":\"0\"}'; if (mutation === 'oversize' || mutation === 'exact') raw += ' '.repeat((mutation === 'exact' ? 1024 : 1025) - new TextEncoder().encode(raw).length); opts.serializedBody = raw; }")
        native = _replace_once(native, "await opts.responseValidator(data);", "(globalThis as any).__vuoroOracle.responseValidator++;\n(globalThis as any).__vuoroOracle.nativeSuccessBody = data;\nawait (globalThis as any).__vuoroOracle.beforeSuccess?.();\nawait opts.responseValidator(data);")
        native = _replace_once(native, "const textError = await response.text();", "(globalThis as any).__vuoroOracle.errorParse++;\nconst textError = await response.text();")
        path.write_text(native)
    entry = stage / "oracle.ts"
    entry.write_text(runner)
    output = stage / "oracle.mjs"
    # Programmatic esbuild uses exact tool modules; no npx, PATH or install.
    program = """import {pathToFileURL} from 'node:url';
const [api, entry, outfile, modules] = process.argv.slice(1);
const {build} = await import(pathToFileURL(api).href);
await build({entryPoints:[entry], outfile, bundle:true, platform:'node', format:'esm', target:'node24', nodePaths:[modules], logLevel:'error'});"""
    run([executable("VUORO_CONTRACT_NODE"), "--input-type=module", "-e", program,
         str(TOOLS / "node_modules/esbuild/lib/main.js"), str(entry), str(output), str(TOOLS / "node_modules")])
    return output


