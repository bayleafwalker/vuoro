def test_two_clean_generations_default_check_and_owner_resource_load(tmp_path, generated):
    before = inventory(SOURCE)
    second = tmp_path / "independent"
    assert invoke(second, "--write") == 0
    assert inventory(generated) == inventory(second)
    saved = inventory(second)
    assert invoke(second) == 0 and inventory(second) == saved
    assert inventory(SOURCE) == before
    manifest = json.loads((second / "operation-manifest.json").read_bytes())
    assert set(manifest["operations"]) == {"submit", "inspect", "empty", "nullBody"}
    assert manifest["operations"]["submit"]["responses"]["400"] != manifest["operations"]["submit"]["responses"]["503"]
    assert manifest["operations"]["empty"]["responses"] == {"204": None}
    null_id = manifest["operations"]["nullBody"]["responses"]["200"]
    assert isinstance(null_id, str)
    bundle = ContractBundle.load(second, integrity_sha256=sha256((second / "integrity.json").read_bytes()).hexdigest())
    raw = {"revision": "9007199254740995", "enabled": True, "nested": {"label": "x"}}
    assert bundle.validate_request("submit", raw) is raw
    assert bundle.validate_response("nullBody", 200, None) is None
    assert (second / "clients/typescript/validated-sdk.ts").is_file()
    assert (second / "clients/typescript/strict-json.ts").read_bytes() == (TOOLS / "templates/strict-json.ts").read_bytes()
    assert (second / f"clients/python/{PYTHON_PACKAGE}/validated_client.py").is_file()
    python_package = second / "clients/python" / PYTHON_PACKAGE
    assert (python_package / "data/operation-manifest.json").is_file()
    assert (python_package / "data/openapi/contract.openapi.json").is_file()
    assert not (second / "clients/python/vuoro_contracts").exists()
    package_integrity = python_package / "data/integrity.json"
    package_bundle = ContractBundle.load(
        python_package / "data",
        integrity_sha256=sha256(package_integrity.read_bytes()).hexdigest(),
    )
    assert package_bundle.manifest == manifest
    schema = json.loads((second / manifest["schemaBundle"]["path"]).read_bytes())
    validate_bundle(schema)
    assert any(p.name == "sdk.gen.ts" for p in (second / "clients/typescript").rglob("*.ts"))
    # Generated SDK markers supplement source review; they are not authenticity.
    assert "auto-generated by @hey-api/openapi-ts" in (second / "clients/typescript/sdk.gen.ts").read_text()

    # Some generated clients emit a literal URL for a route with no path
    # parameters; binding discovery must handle it alongside `.format(...)` URLs.
    static_root = tmp_path / "static-client"
    static_api = static_root / "api/default"
    static_api.mkdir(parents=True)
    (static_api / "pull.py").write_text(
        "def _get_kwargs(client):\n"
        "    _kwargs = {'method': 'post', 'url': '/internal/execution/v1/pull'}\n"
        "    return _kwargs\n"
        "def sync_detailed(client):\n"
        "    return client.get_httpx_client().request(**_get_kwargs(client))\n"
    )
    static_manifest = {
        "operations": {
            "executionPull": {
                "method": "POST",
                "path": "/internal/execution/v1/pull",
                "parameters": [],
                "request": None,
            }
        }
    }
    binding = generator._derive_python_bindings(
        static_root,
        {"paths": {"/internal/execution/v1/pull": {"post": {"operationId": "executionPull"}}}},
        static_manifest,
        {},
        {},
    )
    assert binding["executionPull"]["module"] == "api.default.pull"
    assert binding["executionPull"]["parameters"] == {}


@pytest.mark.parametrize("projection", ["manifest", "schema", "openapi", "python", "typescript", "python_attachment", "typescript_attachment", "decoder", "extra", "missing"])
def test_real_projection_or_attachment_mutation_fails_read_only_check(tmp_path, generated, projection):
    out = tmp_path / "out"
    shutil.copytree(generated, out)
    paths = {"manifest": out / "operation-manifest.json",
             "schema": next((out / "schema").glob("*.json")),
             "openapi": next((out / "openapi").glob("*.json")),
             "python": out / f"clients/python/{PYTHON_PACKAGE}/api/default/submit.py",
             "typescript": out / "clients/typescript/sdk.gen.ts",
             "python_attachment": out / f"clients/python/{PYTHON_PACKAGE}/validated_client.py",
             "typescript_attachment": out / "clients/typescript/validated-sdk.ts",
             "decoder": out / "clients/typescript/strict-json.ts"}
    if projection == "extra": (out / "unknown.bin").write_bytes(b"unexpected")
    elif projection == "missing": (out / "operation-manifest.json").unlink()
    else:
        path = paths[projection]
        path.write_bytes(path.read_bytes() + b" ")
    mutated = inventory(out)
    with pytest.raises(ContractError): invoke(out, "--check")
    assert inventory(out) == mutated


def test_source_change_requires_actual_emission_not_cached_fixture_output(tmp_path, generated):
    source = tmp_path / "owner-source"
    shutil.copytree(SOURCE, source, ignore=shutil.ignore_patterns("node_modules", ".venv"))
    path = source / "main.tsp"
    authored = path.read_text()
    assert authored.count("label: string;") == 1
    path.write_text(authored.replace("label: string;", "renamed_f1b: string;"))
    output = tmp_path / "variant"
    assert invoke(output, "--write", source=source) == 0
    assert inventory(output) != inventory(generated)
    bundle = ContractBundle.load(output, integrity_sha256=sha256((output / "integrity.json").read_bytes()).hexdigest())
    changed = {"revision": "0", "enabled": True, "nested": {"renamed_f1b": "x"}}
    assert bundle.validate_request("submit", changed) is changed
    with pytest.raises(ContractError): bundle.validate_request("submit", {"revision": "0", "enabled": True, "nested": {"label": "x"}})


