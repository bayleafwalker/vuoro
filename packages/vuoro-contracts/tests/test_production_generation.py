def invoke(output, *mode, source=SOURCE):
    return generator.main(["--source", str(source), "--output", str(output), "--contract-id", "probe/v1", *mode])


def inventory(root):
    return {p.relative_to(root).as_posix(): sha256(p.read_bytes()).hexdigest()
            for p in root.rglob("*") if p.is_file()}


def executable(variable):
    # Explicit root-qualified binary only. Missing qualification is a failure.
    value = os.environ[variable]
    path = Path(value)
    assert path.is_absolute() and path.is_file(), variable
    return str(path)


def run(command, *, env=None):
    result = subprocess.run(command, cwd=ROOT, env=env, text=True, capture_output=True, timeout=90)
    assert result.returncode == 0, result.stdout + result.stderr
    return result.stdout


